package vn.edu.fpt.model;

public class MovieGenre {
    private int movieId;
    private int genreId;

    public MovieGenre() {
    }

    public int getMovieId() {
        return movieId;
    }

    public void setMovieId(int movieId) {
        this.movieId = movieId;
    }

    public int getGenreId() {
        return genreId;
    }

    public void setGenreId(int genreId) {
        this.genreId = genreId;
    }
}
